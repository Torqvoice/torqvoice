/**
 * Applying the workshop's tax ends in a page reload, and a reload over
 * unsaved edits loses them. So the edits are saved first, and when that save
 * does not go through (the form refuses a row, the document has locked)
 * nothing is applied and nothing is reloaded.
 */

import { renderHook } from '@testing-library/react'
import { beforeEach, describe, expect, it, vi } from 'vitest'

vi.mock('@/features/settings/Actions/applyWorkshopTaxToDocument', () => ({
  applyWorkshopTaxToDocument: vi.fn(),
}))

import { applyWorkshopTaxToDocument } from '@/features/settings/Actions/applyWorkshopTaxToDocument'
import { useTaxOfferValue } from '@/features/settings/Components/WorkshopTaxOffer'
import { recurringTaxableSubtotal } from '@/lib/taxable-lines'

const reload = vi.fn()

beforeEach(() => {
  vi.resetAllMocks()
  Object.defineProperty(window, 'location', {
    configurable: true,
    value: { ...window.location, reload },
  })
})

function offer(saveFirst: () => Promise<boolean>, taxRate = 0) {
  return renderHook(() =>
    useTaxOfferValue({
      offer: { rate: 25, currentRate: 0 },
      kind: 'workOrder',
      id: 'sr-1',
      locked: false,
      finished: false,
      taxRate,
      saveFirst,
      unsavedMessage: 'Save your changes first, then apply the tax.',
    })
  ).result.current
}

describe('taking the offer from the page', () => {
  it('saves, applies and reloads when the save went through', async () => {
    vi.mocked(applyWorkshopTaxToDocument).mockResolvedValue({ success: true } as never)
    const saveFirst = vi.fn().mockResolvedValue(true)

    await offer(saveFirst)?.apply()

    expect(saveFirst).toHaveBeenCalledTimes(1)
    expect(applyWorkshopTaxToDocument).toHaveBeenCalledWith({ kind: 'workOrder', id: 'sr-1' })
    expect(reload).toHaveBeenCalledTimes(1)
  })

  it('applies nothing and keeps the page when the save did not go through', async () => {
    const value = offer(vi.fn().mockResolvedValue(false))

    await expect(value?.apply()).rejects.toThrow('Save your changes first')

    expect(applyWorkshopTaxToDocument).not.toHaveBeenCalled()
    expect(reload).not.toHaveBeenCalled()
  })

  it('keeps the page when the server refuses, and passes on its reason', async () => {
    vi.mocked(applyWorkshopTaxToDocument).mockResolvedValue({
      success: false,
      error: 'This invoice is locked',
    } as never)

    await expect(offer(vi.fn().mockResolvedValue(true))?.apply()).rejects.toThrow(
      'This invoice is locked'
    )
    expect(reload).not.toHaveBeenCalled()
  })

  it('is withdrawn once the rate on screen is already the workshop rate', () => {
    expect(offer(vi.fn(), 25)).toBeNull()
  })
})

describe('the recurring invoice list', () => {
  it('previews a template with the rule its invoice is generated by', () => {
    // The list and the generator call this one function, so a shop fee is
    // taxed the same in the figure shown and in the invoice that follows.
    const template = {
      cost: 0,
      templateParts: [{ quantity: 1, unitPrice: 100 }],
      templateLabor: [
        { hours: 2, rate: 50, pricingType: 'hourly' },
        { hours: 1, rate: 10, pricingType: 'shopFee' },
      ],
    }
    expect(recurringTaxableSubtotal(template, { parts: true, labor: false, shopFee: true })).toBe(
      110
    )
  })
})
