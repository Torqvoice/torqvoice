/**
 * What a spreadsheet column can become.
 *
 * Every importable field is listed once here, with the header names it is
 * known by. The synonyms are matched after `normalizeHeader` has lowercased
 * the header, stripped accents and dropped everything that is not a letter or
 * digit, so `"E-mail"`, `"E-Mail 1 - Value"` and `"email"` all land on the
 * same key. The list is deliberately multilingual: a Polish shop's export says
 * "Nr rejestracyjny", a German one "Kennzeichen", a Norwegian one "Reg.nr",
 * and all of them are the licence plate.
 *
 * Keys are `<group>.<name>`. The group says which record the value belongs
 * to; an import of vehicles carries an optional owner, an import of service
 * history carries the vehicle and, optionally, the owner.
 */

export type ImportEntity = 'customers' | 'vehicles' | 'services'
export type FieldGroup = 'customer' | 'vehicle' | 'service'
export type FieldType =
  | 'text'
  | 'email'
  | 'phone'
  | 'date'
  | 'number'
  | 'integer'
  | 'year'
  | 'vin'
  | 'plate'
  | 'fuel'
  | 'transmission'

export interface ImportField {
  key: string
  group: FieldGroup
  type: FieldType
  /** Normalised header names this column is commonly called. */
  synonyms: readonly string[]
  /** Header used when we write a template file. */
  templateHeader: string
  /** Example value for the template file. */
  example: string
}

