/** Which groups an entity's mapping can carry. */
export function groupsFor(entity: ImportEntity): FieldGroup[] {
  switch (entity) {
    case 'customers':
      return ['customer']
    case 'vehicles':
      return ['vehicle', 'customer']
    case 'services':
      return ['service', 'vehicle', 'customer']
  }
}

export function fieldsFor(entity: ImportEntity): ImportField[] {
  const groups = new Set(groupsFor(entity))
  return IMPORT_FIELDS.filter((f) => groups.has(f.group))
}

